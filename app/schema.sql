CREATE TABLE public.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "eventName" TEXT,
    "eventDate" DATE,
    "eventTime" TIME WITHOUT TIME ZONE,
    "eventDescription" TEXT,
    "eventAttendanceType" TEXT,
    "maximumAllowed" INTEGER,
    "acceptedEventInformation" TEXT,
    "creatorKeyHash" TEXT,
    "canceled" BOOLEAN NOT NULL DEFAULT FALSE,
    "reservedCount" INTEGER NOT NULL DEFAULT 0 CHECK ("reservedCount" >= 0)
);

CREATE TABLE public.attendees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "eventId" BIGINT,
    "name" TEXT,
    "guestCount" INTEGER NOT NULL DEFAULT 1 CHECK ("guestCount" IN (1, 2)),
    "reservationKeyHash" TEXT,
    CONSTRAINT attendees_event_reservation_key UNIQUE ("eventId", "reservationKeyHash")
);